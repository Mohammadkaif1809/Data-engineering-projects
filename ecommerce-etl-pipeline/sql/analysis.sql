-- Find the cities that have more than 100 orders.
SELECT Shipping_City,COUNT(Order_ID) AS "Orders"
FROM ecommerce_transactions
GROUP BY Shipping_City
HAVING COUNT(Order_ID)>100;

-- Find the countries whose total revenue is greater than $10,000.
SELECT Country,SUM(Total_Amount) AS "Total_Revenue"
FROM ecommerce_transactions
