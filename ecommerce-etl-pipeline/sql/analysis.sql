-- Business: Management wants to identify their highest-value customers.

SELECT 
	Customer_ID,
    SUM(Total_Amount) AS 'Total_Amount',
    COUNT(Order_ID) AS 'Total_Orders',
    DENSE_RANK() OVER(ORDER BY SUM(Total_Amount) DESC ,COUNT(Order_ID) DESC) 'Customer_Rank'
FROM ecommerce_transactions
GROUP BY Customer_ID
ORDER BY Customer_Rank;

-- Top 3 Customers in Each Country
SELECT * FROM (
SELECT 
	Country,
    Customer_ID,
    SUM(Total_Amount) AS 'Total_Amount',
    COUNT(Order_ID) AS 'Total_Orders',
    DENSE_RANK() OVER(PARTITION BY Country ORDER BY SUM(Total_Amount) DESC, COUNT(Order_ID) DESC) AS 'Customer_Rank'
FROM ecommerce_transactions
GROUP BY Country,Customer_ID) AS t
WHERE Customer_Rank<4;

-- The company wants to compare the performance of product categories.
SELECT 
	Product_Category,
    COUNT(Order_ID) AS 'Orders',
    RANK() OVER(ORDER BY COUNT(Order_ID) DESC) 'Rank'
FROM ecommerce_transactions
GROUP BY Product_Category;

-- Business: The finance team wants to monitor month-over-month performance.

SELECT
	YEAR(Order_Date) 'Year',
	MONTHNAME(Order_Date)'MonthName',
    MONTH(Order_Date)'MonthNumber',
    SUM(Total_Amount) 'MonthRevenue',
    
    LAG(SUM(Total_Amount)) OVER(ORDER BY YEAR(Order_Date),MONTH(Order_Date),MONTHNAME(Order_Date))'Previous_Month_Total',
    
    (SUM(Total_Amount) - LAG(SUM(Total_Amount)) OVER(ORDER BY YEAR(Order_Date), MONTH(Order_Date),MONTHNAME(Order_Date))) AS 'Difference',
    
    CONCAT(ROUND(
        (
            (SUM(Total_Amount) - LAG(SUM(Total_Amount)) OVER (ORDER BY YEAR(Order_Date), MONTH(Order_Date)))
            / LAG(SUM(Total_Amount)) OVER (ORDER BY YEAR(Order_Date), MONTH(Order_Date))
        ) * 100.0, 
        2),'%'
    ) AS MoM_Percentage_Change
FROM ecommerce_transactions
GROUP BY YEAR(Order_Date),MONTH(Order_Date),MONTHNAME(Order_Date);

-- Management wants to see how revenue accumulates throughout each year.
SELECT 
	YEAR(Order_Date) 'Year',
    MONTH(Order_Date) 'Month_Num',
    MONTHNAME(Order_Date) 'Month',
    SUM(Total_Amount),
    SUM(SUM(Total_Amount)) OVER(PARTITION BY YEAR(Order_Date) ORDER BY MONTH(Order_Date)) 'YTD_Cumulative_Revenue'
FROM ecommerce_transactions
GROUP BY YEAR(Order_Date),MONTH(Order_Date), MONTHNAME(Order_Date)
ORDER BY YEAR(Order_Date),MONTH(Order_Date)
