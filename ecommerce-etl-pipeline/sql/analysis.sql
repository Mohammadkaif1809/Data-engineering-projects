SELECT Product_Category,SUM(Quantity) 'Total_Quantity_Sold'
FROM ecommerce_transactions
GROUP BY Product_Category;

-- Find the revenue generated by each payment method.
SELECT Payment_Method,SUM(Total_Amount) 'Revenue_generated'
FROM ecommerce_transactions
